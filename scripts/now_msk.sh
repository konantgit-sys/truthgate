#!/bin/bash
# Единственный источник времени для меток в текстах.
# Причина существования: три раза подряд я подписывал доклады временем, которое
# оценивал по длительности своих шагов, а не брал из системы — и забегал вперёд.
# Правило: метку берём ЗДЕСЬ и вписываем ровно её, без добавок «на выполнение».
TZ=Europe/Moscow date "${1:-+%d.%m.%Y %H:%M МСК}"
